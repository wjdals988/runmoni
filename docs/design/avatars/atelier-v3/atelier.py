 if pose==(0,2):
  # The coarse inherited hand plate includes the crimson fabric in this window.
  origin=im.load(); hand_mask=hands.load()
  for y in range(231,250):
   for x in range(108,130):
    r,g,b,a=origin[x,y]
    red_fabric=r>=170 and r>g*1.65 and 40<=b<=95 and g<b*1.5
    pale_seam=(x,y) in {(114,238),(115,239)} or (x>=114 and r>=200 and g>=164 and b>=175 and abs(r-g)<=36 and abs(g-b)<=33)
